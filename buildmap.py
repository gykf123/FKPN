import pickle
import os

def save_map(level_num, map_data):
    """保存关卡数据到 pkl 文件"""
    filename = f"map{level_num}.pkl"
    with open(filename, "wb") as f:
        pickle.dump(map_data, f)
    print(f"[成功] 生成关卡 {level_num}: {filename}")

